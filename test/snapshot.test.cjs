'use strict'

const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const { fixture, state } = require('./helpers.cjs')
const watcher = require('../lib/adapter.cjs')

test('real snapshot diffs across processes, filtering, corruption and policy identity', async t => {
  const root = await fixture(t)
  const snapshot = path.join(state, 'snapshot')
  await fs.writeFile(path.join(root, 'before'), 'one')
  await fs.mkdir(path.join(root, 'node_modules'))
  await fs.writeFile(path.join(root, 'node_modules/ignored'), 'one')
  const options = { ignore: ['**/node_modules/**'], backend: 'inotify' }
  const script = 'const w=require(process.argv[1]);w[process.argv[2]](process.argv[3],process.argv[4],JSON.parse(process.argv[5])).then(x=>console.log(JSON.stringify(x||null))).catch(e=>{console.error(e.message);process.exitCode=1})'
  const child = method => execFileSync(process.execPath, ['-e', script, require.resolve('../lib/adapter.cjs'), method, root, snapshot, JSON.stringify(options)], { encoding: 'utf8', timeout: 10000 })
  child('writeSnapshot')
  await fs.rename(path.join(root, 'before'), path.join(root, 'after'))
  await fs.writeFile(path.join(root, 'new'), 'new')
  await fs.appendFile(path.join(root, 'node_modules/ignored'), 'two')
  const events = JSON.parse(child('getEventsSince'))
  assert(events.some(e => e.path === path.join(root, 'before') && e.type === 'delete'))
  assert(events.some(e => e.path === path.join(root, 'after') && e.type === 'create'))
  assert(events.some(e => e.path === path.join(root, 'new') && e.type === 'create'))
  assert(!events.some(e => e.path.includes('node_modules')))
  await assert.rejects(watcher.getEventsSince(root, snapshot), /policy mismatch/)
  const original = await fs.readFile(snapshot)
  await fs.writeFile(snapshot, Buffer.concat([Buffer.from('X'), original.subarray(1)]))
  await assert.rejects(watcher.getEventsSince(root, snapshot, options), /prefix checksum mismatch/)
  await fs.writeFile(snapshot, 'bad')
  await assert.rejects(watcher.getEventsSince(root, snapshot, options), /incompatible snapshot/)
})

test('snapshot replacement is atomic and brute-force is query-only', async t => {
  const root = await fixture(t)
  const snapshot = path.join(state, 'atomic-snapshot')
  await fs.writeFile(path.join(root, 'file'), 'one')
  await watcher.writeSnapshot(root, snapshot, { backend: 'brute-force' })
  const before = await fs.readFile(snapshot)
  await fs.mkdir(path.join(root, 'denied'), { mode: 0 })
  t.after(() => fs.chmod(path.join(root, 'denied'), 0o700).catch(error => { if (error.code !== 'ENOENT') throw error }))
  await assert.rejects(watcher.writeSnapshot(root, snapshot), /Permission denied/)
  assert.deepEqual(await fs.readFile(snapshot), before)
  await fs.chmod(path.join(root, 'denied'), 0o700)
  await fs.appendFile(path.join(root, 'file'), 'two')
  const events = await watcher.getEventsSince(root, snapshot, { backend: 'brute-force' })
  assert(events.some(e => e.path === path.join(root, 'file') && e.type === 'update'))
  assert(!(await fs.readdir(state)).some(name => name.endsWith('.tmp')))
})
